public class AgentParcelCountingStream : System.IO.Stream {
    private long _count;
    public long Count { get { return _count; } }
    public override bool CanRead { get { return false; } }
    public override bool CanSeek { get { return false; } }
    public override bool CanWrite { get { return true; } }
    public override long Length { get { return _count; } }
    public override long Position { get { return _count; } set { throw new System.NotSupportedException(); } }
    public override void Flush() { }
    public override int Read(byte[] buffer, int offset, int count) { throw new System.NotSupportedException(); }
    public override long Seek(long offset, System.IO.SeekOrigin origin) { throw new System.NotSupportedException(); }
    public override void SetLength(long value) { throw new System.NotSupportedException(); }
    public override void Write(byte[] buffer, int offset, int count) { _count += count; }
}
'@
}

