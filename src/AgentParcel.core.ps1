    return (New-Object PSObject -Property @{ Kind = $Kind; Name = $Name; Entry = $Entry; Comp = $Comp; Cost = $Cost; Len = $Len; IsManifest = $false })
}

function Add-ZsArchiveItems($Archive, [string]$Prefix, $Items, [long]$Budget, [bool]$Unpack, [int]$Depth, [int]$ArchiveId) {
    # Measures every entry of $Archive, appends work items to $Items and manifest records.
    # Inner .zip entries are (optionally) unpacked recursively via temp files.
    $entries = @($Archive.Entries)
    $names = New-Object 'System.Collections.Generic.HashSet[string]' ([System.StringComparer]::OrdinalIgnoreCase)
    foreach ($en in $entries) { [void]$names.Add($en.FullName.Replace('\', '/')) }
    foreach ($en in $entries) {
        $name = $Prefix + $en.FullName
        $isDir = $en.FullName.EndsWith('/') -or $en.FullName.EndsWith('\')
        if ($isDir) {
            $Items.Add((New-ZsItem 'dir' $name $en 0 (Get-ZsEntryOverhead $name) 0))
            $script:ZsMEntries.Add((ConvertTo-ZsJsonObject @('archive', $ArchiveId, 'name', $en.FullName, 'type', 'dir', 'stored', $name, 'time', (Get-ZsTimeString $en))))
            continue
        }
        if ($Unpack -and $Depth -lt 20 -and $en.FullName.ToLowerInvariant().EndsWith('.zip')) {
            $ok = Expand-ZsInnerZip $en $name $names $Items $Budget $Depth $ArchiveId
            if ($ok -eq $true) { continue }
        }
        Report-ZsProgress ('Analyzing ' + $name)
        $m = Measure-ZsEntry $en
        $cost = $m.Comp + (Get-ZsEntryOverhead $name)
        $kind = 'file'
        if ($cost -gt $Budget) { $kind = 'chunked' }
        $Items.Add((New-ZsItem $kind $name $en $m.Comp $cost $en.Length))
        $script:ZsMEntries.Add((ConvertTo-ZsJsonObject @('archive', $ArchiveId, 'name', $en.FullName, 'type', 'file', 'stored', $name, 'size', [long]$en.Length, 'sha256', $m.Sha, 'split', ($kind -eq 'chunked'), 'time', (Get-ZsTimeString $en))))
    }
}

function Expand-ZsInnerZip($Entry, [string]$Name, $SiblingNames, $Items, [long]$Budget, [int]$Depth, [int]$ParentId) {
    # Returns $true if the inner zip was opened and all its entries were added.
    $folder = $Name.Substring(0, $Name.Length - 4)
    $rel = $Entry.FullName.Replace('\', '/')
    $relFolder = $rel.Substring(0, $rel.Length - 4) + '/'
    $clash = $false
    foreach ($n in $SiblingNames) { if ($n.StartsWith($relFolder, [System.StringComparison]::OrdinalIgnoreCase)) { $clash = $true; break } }
    if ($clash) { $prefix = $folder + '_unzipped/' } else { $prefix = $folder + '/' }

    Report-ZsProgress ('Unpacking ' + $Name)
    $tmp = Join-Path $script:ZsTempDir ([guid]::NewGuid().ToString('N') + '.zip')
    $innerFs = $null
    $inner = $null
    $adjust = 0.0
    $zipSha = ''
    $sub = [System.Collections.Generic.List[object]]::new()
    $saveE = $script:ZsMEntries.Count
    $saveA = $script:ZsMArchives.Count
    $script:ZsArchiveCounter++
    $myId = $script:ZsArchiveCounter
    try {
        $hasher = New-ZsHasher
        $src = $Entry.Open()
        $out = New-Object System.IO.FileStream($tmp, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::Write)
        try { Copy-ZsStream $src $out $hasher } finally { $src.Dispose(); $out.Dispose() }
        $zipSha = Complete-ZsHasher $hasher
        $innerFs = New-Object System.IO.FileStream($tmp, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read)
        $inner = New-Object System.IO.Compression.ZipArchive($innerFs, [System.IO.Compression.ZipArchiveMode]::Read, $false)
        $innerTotal = 0.0
        foreach ($ie in $inner.Entries) { $innerTotal += $ie.Length }
        $adjust = 2.0 * $innerTotal - [double]$Entry.Length
        $script:ZsTotalWork += $adjust
        $script:ZsMArchives.Add((ConvertTo-ZsJsonObject @('id', $myId, 'parent', $ParentId, 'depth', ($Depth + 1), 'entry', $Entry.FullName, 'folder', $prefix)))
        Add-ZsArchiveItems $inner $prefix $sub $Budget $true ($Depth + 1) $myId
        if ($sub.Count -eq 0) { $sub.Add((New-ZsItem 'dir' $prefix $Entry 0 (Get-ZsEntryOverhead $prefix) 0)) }
    }
    catch {
        $msg = $_.Exception.Message
        if ($inner) { $inner.Dispose() } elseif ($innerFs) { $innerFs.Dispose() }
        if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
        $script:ZsTotalWork -= $adjust
        if ($script:ZsMEntries.Count -gt $saveE) { $script:ZsMEntries.RemoveRange($saveE, $script:ZsMEntries.Count - $saveE) }
        if ($script:ZsMArchives.Count -gt $saveA) { $script:ZsMArchives.RemoveRange($saveA, $script:ZsMArchives.Count - $saveA) }
        $script:ZsUnpackFailed.Add($Name + '  (' + $msg + ')')
        return $false
    }
    $script:ZsOpened.Add($inner)
    foreach ($s in $sub) { $Items.Add($s) }
    $script:ZsUnpacked.Add($Name)
    $script:ZsMEntries.Add((ConvertTo-ZsJsonObject @('archive', $ParentId, 'name', $Entry.FullName, 'type', 'zip', 'zip', $myId, 'folder', $prefix, 'size', [long]$Entry.Length, 'sha256', $zipSha, 'time', (Get-ZsTimeString $Entry))))
    return $true
}


function Remove-ZsOwned($Owned, [string]$Directory, [bool]$CreatedDir) {
    foreach ($p in @($Owned)) {
        if ($p -and (Test-Path -LiteralPath $p)) {
            Remove-Item -LiteralPath $p -Force -ErrorAction SilentlyContinue
        }
    }
    if ($CreatedDir -and $Directory -and (Test-Path -LiteralPath $Directory -PathType Container)) {
        if (@(Get-ChildItem -LiteralPath $Directory -Force -ErrorAction SilentlyContinue).Count -eq 0) {
            Remove-Item -LiteralPath $Directory -Force -ErrorAction SilentlyContinue
        }
    }
}

function Get-ZsSha256File([string]$Path) {
    $hasher = New-ZsHasher
    $fs = [System.IO.File]::OpenRead($Path)
    try { Copy-ZsStream $fs $null $hasher } finally { $fs.Dispose() }
    return (Complete-ZsHasher $hasher)
}

function Write-ZsUtf8([string]$Path, [string]$Text) {
    if (-not $Text.EndsWith("`n")) { $Text += "`n" }
    $enc = New-Object System.Text.UTF8Encoding $false
    [System.IO.File]::WriteAllText($Path, ($Text -replace "`r`n", "`n"), $enc)
    return $Path
}

