function Report-ZsProgress([string]$Message) {
    if ($script:ZsCancel) { throw 'Cancelled' }
    if ($Message) { $script:ZsStatus = $Message }
    $pct = [int][Math]::Floor(100.0 * $script:ZsDoneWork / [Math]::Max(1.0, $script:ZsTotalWork))
    if ($pct -gt 100) { $pct = 100 }
    if ($pct -lt 0) { $pct = 0 }
    if ($script:ZsProgress -and ($pct -ne $script:ZsLastPct -or $Message)) {
        $script:ZsLastPct = $pct
        & $script:ZsProgress $pct $script:ZsStatus
    }
    if ($script:ZsCancel) { throw 'Cancelled' }
}

function Copy-ZsStream($Source, $Destination, $Hasher) {
    # Copies a stream in 1 MB blocks, optionally hashing, and reports progress (work units = bytes).
    $buf = New-Object byte[] 1048576
    while ($true) {
        $n = $Source.Read($buf, 0, $buf.Length)
        if ($n -le 0) { break }
        if ($Hasher) { [void]$Hasher.TransformBlock($buf, 0, $n, $null, 0) }
        if ($Destination) { $Destination.Write($buf, 0, $n) }
        $script:ZsDoneWork += $n
        Report-ZsProgress $null
    }
}

function New-ZsHasher { return [System.Security.Cryptography.SHA256]::Create() }

function Complete-ZsHasher($Hasher) {
    [void]$Hasher.TransformFinalBlock((New-Object byte[] 0), 0, 0)
    $h = [System.BitConverter]::ToString($Hasher.Hash).Replace('-', '').ToLowerInvariant()
    $Hasher.Dispose()
    return $h
}

function Measure-ZsEntry($Entry) {
    # Compresses the entry's data into a byte counter (real compressed size) and hashes it.
    $counter = New-Object AgentParcelCountingStream
    $deflate = New-Object System.IO.Compression.DeflateStream($counter, [System.IO.Compression.CompressionLevel]::Optimal, $true)
    $hasher = New-ZsHasher
    $src = $Entry.Open()
    try { Copy-ZsStream $src $deflate $hasher } finally { $src.Dispose(); $deflate.Dispose() }
    $sha = Complete-ZsHasher $hasher
    return (New-Object PSObject -Property @{ Comp = $counter.Count; Sha = $sha })
}

function Get-ZsDeflatedSizeOfBytes([byte[]]$Buffer, [int]$Count) {
    $counter = New-Object AgentParcelCountingStream
    $deflate = New-Object System.IO.Compression.DeflateStream($counter, [System.IO.Compression.CompressionLevel]::Optimal, $true)
    try { $deflate.Write($Buffer, 0, $Count) } finally { $deflate.Dispose() }
    return $counter.Count
}

function Get-ZsEntryOverhead([string]$Name) {
    # local header (30) + central dir record (46) + name twice + room for zip64 extras / descriptor
    $nb = [System.Text.Encoding]::UTF8.GetByteCount($Name)
    return [long](30 + 46 + 2 * $nb + 96)
}

