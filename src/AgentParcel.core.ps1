if ($env:AGENTPARCEL_LAYOUT_TEST -eq '1') {
    # Self-test (no window is shown, nothing is written): lay the form out and check every control is inside the window.
    function Get-ZsFormRect($Ctl) {
        $x = 0; $y = 0; $c = $Ctl
        while ($c -and $c -ne $form) { $x += $c.Left; $y += $c.Top; $c = $c.Parent }
        return New-Object System.Drawing.Rectangle($x, $y, $Ctl.Width, $Ctl.Height)
    }
    function Get-ZsAllControls($Parent) { foreach ($c in $Parent.Controls) { $c; Get-ZsAllControls $c } }
    # The form really is shown (so WinForms lays out every tab exactly as it would for the user),
    # but fully transparent, off-screen and without a taskbar button.
    $form.StartPosition = 'Manual'
    $form.Location = New-Object System.Drawing.Point(-30000, -30000)
    $form.ShowInTaskbar = $false
    $form.Opacity = 0
    $form.Show()
    [System.Windows.Forms.Application]::DoEvents()
    $problems = 0
    foreach ($size in @('normal', 'minimum')) {
        if ($size -eq 'minimum') { $form.Size = $form.MinimumSize; [System.Windows.Forms.Application]::DoEvents() }
        foreach ($page in @($tabSplit, $tabJoin)) {
            $tabs.SelectedTab = $page
            [System.Windows.Forms.Application]::DoEvents()
            $form.PerformLayout(); $main.PerformLayout(); $page.PerformLayout()
            [System.Windows.Forms.Application]::DoEvents()
            $client = $form.ClientRectangle
            foreach ($c in @(Get-ZsAllControls $form)) {
                if ($c -is [System.Windows.Forms.TabPage] -and $c -ne $page) { continue }
                if ($c.Parent -is [System.Windows.Forms.TabPage] -and $c.Parent -ne $page) { continue }
                $owner = $c; $hidden = $false
                while ($owner) { if ($owner -is [System.Windows.Forms.TabPage] -and $owner -ne $page) { $hidden = $true }; $owner = $owner.Parent }
                if ($hidden) { continue }
                $rc = Get-ZsFormRect $c
                $pr = $c.Parent.ClientRectangle
                $bad = @()
                if ($rc.Right -gt $client.Right -or $rc.Bottom -gt $client.Bottom -or $rc.Left -lt 0 -or $rc.Top -lt 0) { $bad += 'outside window' }
                if ($c.Right -gt $pr.Right + 1 -or $c.Bottom -gt $pr.Bottom + 1) { $bad += 'outside parent' }
                if ($c.Width -le 0 -or $c.Height -le 0) { $bad += 'zero size' }
                if ($c -is [System.Windows.Forms.ButtonBase]) {
                    $need = [System.Windows.Forms.TextRenderer]::MeasureText($c.Text, $c.Font)
                    if ($c.Width -lt $need.Width -or $c.Height -lt $need.Height) { $bad += 'text clipped' }
                }
                if ($c -eq $dropSplit -or $c -eq $dropJoin) {
                    $need = [System.Windows.Forms.TextRenderer]::MeasureText($c.Text, $c.Font, (New-Object System.Drawing.Size(($c.Width - 4), 0)), [System.Windows.Forms.TextFormatFlags]::WordBreak)
                    if ($need.Height -gt $c.Height) { $bad += 'wrapped text taller than label' }
                }
                if ($bad.Count -gt 0) { $problems++; Write-Output ('PROBLEM [{0}/{1}] {2} "{3}" at {4}: {5}' -f $size, $page.Text, $c.GetType().Name, $c.Text, $rc, ($bad -join ', ')) }
            }
        }
        Write-Output ('{0}: window {1}x{2}, client {3}x{4}, log {5}x{6}' -f $size, $form.Width, $form.Height, $form.ClientSize.Width, $form.ClientSize.Height, $log.Width, $log.Height)
        if ($env:AGENTPARCEL_LAYOUT_PNG -eq '1') {
            # picture of each tab as base64 PNG on stdout (nothing is written to disk)
            foreach ($page in @($tabSplit, $tabJoin)) {
                $tabs.SelectedTab = $page; [System.Windows.Forms.Application]::DoEvents()
                $bmp = New-Object System.Drawing.Bitmap($form.Width, $form.Height)
                $form.DrawToBitmap($bmp, (New-Object System.Drawing.Rectangle(0, 0, $form.Width, $form.Height)))
                $ms = New-Object System.IO.MemoryStream
                $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png); $bmp.Dispose()
                Write-Output ('PNG {0} {1} {2}' -f $size, $page.Text.Replace(' ', '_'), [Convert]::ToBase64String($ms.ToArray()))
            }
        }
    }
    $btns = @($browse, $splitBtn, $addParts, $addFolder, $clearParts, $outBrowse, $verifyBtn, $resendBtn, $joinBtn, $openBtn, $stopBtn) | ForEach-Object { '{0}={1}x{2}' -f $_.Text, $_.Width, $_.Height }
    Write-Output ('scale {0}: buttons {1}' -f $script:S, ($btns -join '; '))
    if ($form.Icon) {
        foreach ($isz in 16, 32, 48) {
            $ic = New-Object System.Drawing.Icon($form.Icon, $isz, $isz); $ib = $ic.ToBitmap()
            $ims = New-Object System.IO.MemoryStream; $ib.Save($ims, [System.Drawing.Imaging.ImageFormat]::Png)
            Write-Output ('ICON {0}x{1} {2}' -f $ib.Width, $ib.Height, $(if ($env:AGENTPARCEL_LAYOUT_PNG -eq '1') { [Convert]::ToBase64String($ims.ToArray()) } else { 'ok' }))
            $ib.Dispose(); $ic.Dispose()
        }
    } else { Write-Output 'ICON none' }
    $wa = [System.Windows.Forms.Screen]::PrimaryScreen
    Write-Output ('screen {0}x{1}, working area {2}x{3}' -f $wa.Bounds.Width, $wa.Bounds.Height, $wa.WorkingArea.Width, $wa.WorkingArea.Height)
    Write-Output ('LAYOUT TEST: ' + $(if ($problems -eq 0) { 'OK' } else { "$problems problem(s)" }))
    $form.Close(); $form.Dispose()
    return
}

