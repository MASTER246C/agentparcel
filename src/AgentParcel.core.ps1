function Write-ZsPart([string]$PartPath, $Items) {
    # Items: objects with .Kind = 'dir' | 'file' | 'bytes' | 'text' | 'blob'
    if (Test-Path -LiteralPath $PartPath) { Remove-Item -LiteralPath $PartPath -Force }
    $fs = New-Object System.IO.FileStream($PartPath, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::ReadWrite)
    $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create, $false)
    try {
        foreach ($it in $Items) {
            if ($it.Kind -eq 'dir') {
                $e = $zip.CreateEntry($it.Name)
                Set-ZsEntryTime $e $it.Entry
            }
            elseif ($it.Kind -eq 'file') {
                $e = $zip.CreateEntry($it.Name, [System.IO.Compression.CompressionLevel]::Optimal)
                Set-ZsEntryTime $e $it.Entry
                $dst = $e.Open()
                $src = $it.Entry.Open()
                try { Copy-ZsStream $src $dst $null } finally { $src.Dispose(); $dst.Dispose() }
            }
            elseif ($it.Kind -eq 'bytes') {
                $e = $zip.CreateEntry($it.Name, [System.IO.Compression.CompressionLevel]::Optimal)
                Set-ZsEntryTime $e $it.Entry
                $dst = $e.Open()
                try { $dst.Write($it.Buffer, 0, $it.Count) } finally { $dst.Dispose() }
            }
            elseif ($it.Kind -eq 'text' -or $it.Kind -eq 'blob') {
                $e = $zip.CreateEntry($it.Name, [System.IO.Compression.CompressionLevel]::Optimal)
                if ($it.Kind -eq 'text') { $bytes = [System.Text.Encoding]::UTF8.GetBytes($it.Text) } else { $bytes = $it.Bytes }
                $dst = $e.Open()
                try { $dst.Write($bytes, 0, $bytes.Length) } finally { $dst.Dispose() }
            }
        }
    }
    finally {
        $zip.Dispose()
        $fs.Dispose()
    }
    return (Get-Item -LiteralPath $PartPath).Length
}

function Add-ZsZipEntryText([string]$ZipPath, [string]$EntryName, [string]$Text) {
    # Appends one small entry to an existing zip (Update mode copies the other entries as-is).
    $fs = New-Object System.IO.FileStream($ZipPath, [System.IO.FileMode]::Open, [System.IO.FileAccess]::ReadWrite)
    $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Update, $false)
    try {
        $e = $zip.CreateEntry($EntryName, [System.IO.Compression.CompressionLevel]::Optimal)
        $bytes = [System.Text.Encoding]::UTF8.GetBytes($Text)
        $dst = $e.Open()
        try { $dst.Write($bytes, 0, $bytes.Length) } finally { $dst.Dispose() }
    }
    finally { $zip.Dispose(); $fs.Dispose() }
    return (Get-Item -LiteralPath $ZipPath).Length
}

function Get-ZsRejoinText($SplitInfo) {
    $winName = $SplitInfo.Name.Replace('/', '\')
    $pieces = @()
    foreach ($p in $SplitInfo.Pieces) { $pieces += ('"' + $p.Replace('/', '\') + '"') }
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('This file was too large for one zip part, so it was cut into raw pieces:')
    [void]$sb.AppendLine('  ' + $winName)
    [void]$sb.AppendLine('Pieces: ' + $SplitInfo.Pieces.Count + '  (stored in ' + $SplitInfo.PartNames[0] + ' .. ' + $SplitInfo.PartNames[$SplitInfo.PartNames.Count - 1] + ')')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('Easiest: open AgentParcel, choose "Rebuild from parts" and drop the parts in.')
    [void]$sb.AppendLine('By hand:')
    [void]$sb.AppendLine('1) Extract ALL the part zips into the same folder.')
    [void]$sb.AppendLine('2) Open Command Prompt (cmd.exe) in that folder and run:')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('copy /b ' + ($pieces -join '+') + ' "' + $winName + '"')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('3) After checking the rebuilt file, the .### piece files can be deleted.')
    return $sb.ToString()
}

