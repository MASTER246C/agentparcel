    [void](New-Item -ItemType Directory -Path $d)
    return $d
}

# ---- minimal JSON writer (ASCII-only output, identical on every PowerShell version) ----
function ConvertTo-ZsJsonValue($Value) {
    if ($null -eq $Value) { return 'null' }
    if ($Value -is [bool]) { if ($Value) { return 'true' } else { return 'false' } }
    if ($Value -is [int] -or $Value -is [long] -or $Value -is [double]) { return ([string]$Value) }
    $s = [string]$Value
    $sb = New-Object System.Text.StringBuilder ($s.Length + 2)
    [void]$sb.Append('"')
    foreach ($ch in $s.ToCharArray()) {
        $c = [int]$ch
        if ($ch -eq '"') { [void]$sb.Append('\"') }
        elseif ($ch -eq '\') { [void]$sb.Append('\\') }
        elseif ($c -lt 32 -or $c -gt 126) { [void]$sb.Append('\u' + $c.ToString('x4')) }
        else { [void]$sb.Append($ch) }
    }
    [void]$sb.Append('"')
    return $sb.ToString()
}

function ConvertTo-ZsJsonObject($Pairs) {
    # $Pairs: array of key, value, key, value ... in the order they should be written
    $parts = @()
    for ($k = 0; $k -lt $Pairs.Count; $k += 2) { $parts += ((ConvertTo-ZsJsonValue $Pairs[$k]) + ':' + (ConvertTo-ZsJsonValue $Pairs[$k + 1])) }
    return '{' + ($parts -join ',') + '}'
}

function ConvertFrom-ZsJson([string]$Text) {
    # Windows PowerShell 5.1's ConvertFrom-Json refuses JSON over ~2 MB (big manifests), so use the
    # serializer directly there. Dictionaries support the same $obj.key access as PSCustomObjects.
    if ($PSVersionTable.PSVersion.Major -le 5) {
        Add-Type -AssemblyName System.Web.Extensions
        $ser = New-Object System.Web.Script.Serialization.JavaScriptSerializer
        $ser.MaxJsonLength = [int]::MaxValue
        $ser.RecursionLimit = 1000
        return ,($ser.DeserializeObject($Text))
    }
    return ,($Text | ConvertFrom-Json)
}

function Get-ZsProp($Obj, [string]$Name) {
    if ($null -eq $Obj) { return $null }
    if ($Obj -is [System.Collections.IDictionary]) {
        # (Dictionary<,> only exposes IDictionary.Contains explicitly, so PowerShell 5.1 needs ContainsKey)
        if ($Obj.PSObject.Methods['ContainsKey']) { $has = $Obj.ContainsKey($Name) } else { $has = ([System.Collections.IDictionary]$Obj).Contains($Name) }
        if ($has) { return ,$Obj[$Name] } else { return $null }
    }
    $p = $Obj.PSObject.Properties[$Name]
    if ($p) { return ,$p.Value }
    return $null
}

function Get-ZsItems($Obj, [string]$Name) {
    # Get-ZsProp already returns one value (the comma stops an array from unrolling).
    # Wrapping that call in @() nests the JSON array, so a good part set looks corrupt.
    $value = Get-ZsProp $Obj $Name
    if ($null -eq $value) { $value = @() }
    elseif ($value -isnot [System.Array]) { $value = @($value) }
    return ,$value
}

function Format-ZsLogError([string]$Message) {
    # A WinForms text box only breaks lines on CRLF. A thrown message uses LF, so the
    # log would show every corrupt part on one line.
    if ($null -eq $Message) { return '' }
    return (($Message -replace "`r`n", "`n" -replace "`r", "`n") -replace "`n", "`r`n")
}

function Read-ZsJsonEntry($Entry) {
    $s = $Entry.Open()
    $r = New-Object System.IO.StreamReader($s, [System.Text.Encoding]::UTF8)
    try { $txt = $r.ReadToEnd() } finally { $r.Dispose(); $s.Dispose() }
    return ,(ConvertFrom-ZsJson $txt)
}

