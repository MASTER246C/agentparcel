function Get-ZsPartInfo([string]$FileName) {
    $m = [regex]::Match($FileName, '^(?<base>.+)_part(?<n>\d+)\.zip$', [System.Text.RegularExpressions.RegexOptions]::IgnoreCase)
    if (-not $m.Success) { return $null }
    return (New-Object PSObject -Property @{ Base = $m.Groups['base'].Value; Number = [int]$m.Groups['n'].Value; Width = $m.Groups['n'].Value.Length })
}

function Find-ZsPartSet([string[]]$InputPaths) {
    # Expands folders, and a single part into all of its siblings (<name>_partNN.zip).
    $seen = New-Object 'System.Collections.Generic.HashSet[string]' ([System.StringComparer]::OrdinalIgnoreCase)
    $out = New-Object System.Collections.Generic.List[string]
    $files = New-Object System.Collections.Generic.List[string]
    foreach ($p in $InputPaths) {
        if (-not $p) { continue }
        $p = $p.Trim().Trim('"')
        if (Test-Path -LiteralPath $p -PathType Container) {
            foreach ($f in @(Get-ChildItem -LiteralPath $p -File | Where-Object { $_.Extension -ieq '.zip' -and -not (Test-ZsIsAppsBundleName $_.Name) } | Sort-Object Name)) { $files.Add($f.FullName) }
        }
        elseif (Test-Path -LiteralPath $p -PathType Leaf) { $files.Add((Resolve-Path -LiteralPath $p).ProviderPath) }
        else { throw ('Not found: ' + $p) }
    }
    # several items = exactly these parts; one item (the apps bundle does not count) = find its siblings
    $explicit = (@($InputPaths | Where-Object { $_ -and -not (Test-ZsIsAppsBundleName ([System.IO.Path]::GetFileName($_.Trim().Trim('"')))) }).Count -gt 1)
    foreach ($f in $files) {
        if ($seen.Add($f)) { $out.Add($f) }
        if (-not $explicit) {
            $pinfo = Get-ZsPartInfo ([System.IO.Path]::GetFileName($f))
            if ($pinfo) {
                $dir = [System.IO.Path]::GetDirectoryName($f)
                foreach ($s in @(Get-ChildItem -LiteralPath $dir -File | Sort-Object Name)) {
                    $si = Get-ZsPartInfo $s.Name
                    if ($si -and $si.Base -ieq $pinfo.Base) { if ($seen.Add($s.FullName)) { $out.Add($s.FullName) } }
                }
            }
        }
    }
    return ,$out.ToArray()
}

function Test-ZsLooksLikeParts([string[]]$InputPaths) {
    # Used by the GUI / launcher to decide between Split and Rebuild for dropped items.
    foreach ($p in @($InputPaths)) {
        if (Find-ZsByteManifest @($p)) { return $true }
    }
    $InputPaths = @($InputPaths | Where-Object { -not (Test-ZsIsAppsBundleName ([System.IO.Path]::GetFileName($_))) })
    $zipCount = 0
    foreach ($p in $InputPaths) {
        if (Test-Path -LiteralPath $p -PathType Container) { return $true }
        if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { continue }
        $zipCount++
        try {
            $z = [System.IO.Compression.ZipFile]::OpenRead((Resolve-Path -LiteralPath $p).ProviderPath)
            try { if ($z.GetEntry($script:ZsStubName)) { return $true } } finally { $z.Dispose() }
        } catch { }
    }
    if ($zipCount -gt 1) {
        foreach ($p in $InputPaths) { if (-not (Get-ZsPartInfo ([System.IO.Path]::GetFileName($p)))) { return $false } }
        return $true
    }
    return $false
}

function Find-ZsStoredEntry([string]$Stored) {
    # Returns the part entries holding the file: one entry, or the raw pieces in order.
    $idx = $script:ZsJoinIndex
    if ($idx.ContainsKey($Stored)) { return ,@($idx[$Stored]) }
    foreach ($w in 3, 4, 5, 6) {
        $first = $Stored + '.' + ('1'.PadLeft($w, '0'))
        if ($idx.ContainsKey($first)) {
            $list = [System.Collections.Generic.List[object]]::new()
            $k = 1
            while ($true) {
                $nm = $Stored + '.' + ([string]$k).PadLeft($w, '0')
                if (-not $idx.ContainsKey($nm)) { break }
                $list.Add($idx[$nm]); $k++
            }
            return ,$list.ToArray()
        }
    }
    return ,@()
}

function Write-ZsJoinArchive([int]$ArchiveId, $Zip) {
    # Writes the entries of manifest archive $ArchiveId into $Zip, in original order.
    # Inner zips are rebuilt (recursively, deepest first) into temp files and then added.
    if (-not $script:ZsJoinByArchive.ContainsKey($ArchiveId)) { return }
    $list = $script:ZsJoinByArchive[$ArchiveId]
    foreach ($rec in $list) {
        $name = [string]$rec.name
        if ($rec.type -eq 'dir') {
            $e = $Zip.CreateEntry($name)
            Set-ZsEntryTimeFromString $e $rec.time
        }
        elseif ($rec.type -eq 'file') {
            $srcEntries = Find-ZsStoredEntry ([string]$rec.stored)
            if ($srcEntries.Count -eq 0) { throw ('Missing from the parts: ' + $rec.stored) }
            Report-ZsProgress ('Rebuilding ' + $rec.stored)
            $e = $Zip.CreateEntry($name, [System.IO.Compression.CompressionLevel]::Optimal)
            Set-ZsEntryTimeFromString $e $rec.time
            $hasher = New-ZsHasher
            $count = [long]0
            $dst = $e.Open()
            try {
                foreach ($se in $srcEntries) {
                    $s = $se.Open()
                    try { Copy-ZsStream $s $dst $hasher } finally { $s.Dispose() }
                    $count += $se.Length
                }
            }
            finally { $dst.Dispose() }
            $sha = Complete-ZsHasher $hasher
            if ($count -ne [long]$rec.size -or $sha -ne [string]$rec.sha256) {
                throw ('Verification failed for ' + $rec.stored + ' (got ' + $count + ' bytes, expected ' + $rec.size + '). The parts may be damaged or from different sets.')
            }
            $script:ZsJoinVerified++
        }
        elseif ($rec.type -eq 'zip') {
            Report-ZsProgress ('Re-zipping ' + $name)
            $tmp = Join-Path $script:ZsTempDir ([guid]::NewGuid().ToString('N') + '.zip')
            $fs = New-Object System.IO.FileStream($tmp, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::ReadWrite)
            $inner = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create, $false)
            try { Write-ZsJoinArchive ([int]$rec.zip) $inner } finally { $inner.Dispose(); $fs.Dispose() }
            $e = $Zip.CreateEntry($name, [System.IO.Compression.CompressionLevel]::Optimal)
            Set-ZsEntryTimeFromString $e $rec.time
            $dst = $e.Open()
            $s = [System.IO.File]::OpenRead($tmp)
            try { Copy-ZsStream $s $dst $null } finally { $s.Dispose(); $dst.Dispose() }
            Remove-Item -LiteralPath $tmp -Force
            $script:ZsJoinInnerZips++
        }
    }
}

function Get-ZsJoinOutputPath([string]$OutputDir, [string]$PartsDir, [string]$OriginalName) {
    if ($OutputDir) {
        if (-not (Test-Path -LiteralPath $OutputDir)) { [void](New-Item -ItemType Directory -Path $OutputDir) }
        return (Get-ZsUniquePath (Join-Path (Resolve-Path -LiteralPath $OutputDir).ProviderPath $OriginalName))
    }
    return (Get-ZsUniquePath (Join-Path $PartsDir ([System.IO.Path]::GetFileNameWithoutExtension($OriginalName) + '_rebuilt.zip')))
}

function Invoke-ZipJoin {
    param(
        [Parameter(Mandatory = $true)][string[]]$InputPaths,
        [string]$OutputDir,
        [scriptblock]$OnProgress
    )
    $script:ZsProgress = $OnProgress
    $script:ZsDoneWork = 0.0
    $script:ZsLastPct = -1
    $script:ZsTotalWork = 1.0
    $warnings = New-Object System.Collections.Generic.List[string]

    $files = Find-ZsPartSet $InputPaths
    if ($files.Count -eq 0) { throw 'No .zip parts found.' }
    Report-ZsProgress ('Checking ' + $files.Count + ' part(s)...')

    $opened = [System.Collections.Generic.List[object]]::new()
    $script:ZsTempDir = New-ZsTempDir
    $tmpOut = $null
    try {
        # ---- open parts, read labels ----
        $parts = [System.Collections.Generic.List[object]]::new()
        foreach ($f in $files) {
            try { $z = [System.IO.Compression.ZipFile]::OpenRead($f) }
            catch { throw ('Not a readable zip: ' + [System.IO.Path]::GetFileName($f) + ' (' + $_.Exception.Message + ')') }
            if ($z.GetEntry($script:ZsAppsMarker)) { $z.Dispose(); continue }   # the apps bundle is not a part
            $opened.Add($z)
            $stub = $null
            $se = $z.GetEntry($script:ZsStubName)
            if ($se) { try { $stub = Read-ZsJsonEntry $se } catch { $stub = $null } }
            $parts.Add((New-Object PSObject -Property @{ Path = $f; Zip = $z; Stub = $stub; Info = (Get-ZsPartInfo ([System.IO.Path]::GetFileName($f))) }))
        }
        if ($parts.Count -eq 0) { throw 'No parts found (only the AgentParcel-apps.zip bundle).' }
        $labelled = @($parts | Where-Object { $_.Stub })
        $partsDir = [System.IO.Path]::GetDirectoryName($parts[0].Path)

        if ($labelled.Count -gt 0) {
            # ================= manifest mode =================
            $setId = [string]$labelled[0].Stub.setId
            $partCount = [int]$labelled[0].Stub.partCount
            $origName = [string]$labelled[0].Stub.originalName
            $use = @{}
            foreach ($p in $parts) {
                $fn = [System.IO.Path]::GetFileName($p.Path)
                if (-not $p.Stub) { $warnings.Add('Ignored (not a AgentParcel part): ' + $fn); continue }
                if ([string]$p.Stub.setId -ne $setId) { $warnings.Add('Ignored (belongs to a different split set): ' + $fn); continue }
                $num = [int]$p.Stub.part
                if ($use.ContainsKey($num)) { $warnings.Add('Ignored duplicate of part ' + $num + ': ' + $fn); continue }
                $use[$num] = $p
            }
            $missing = @()
            for ($k = 1; $k -le $partCount; $k++) { if (-not $use.ContainsKey($k)) { $missing += $k } }
            if ($missing.Count -gt 0) {
                $stemName = [System.IO.Path]::GetFileNameWithoutExtension($origName)
                $w = [Math]::Max(2, ([string]$partCount).Length)
                $names = @(); foreach ($k in $missing) { $names += ($stemName + '_part' + ([string]$k).PadLeft($w, '0') + '.zip') }
                $still = @(); for ($i = 0; $i -lt $missing.Count; $i++) { $still += ('part ' + $missing[$i] + ' ' + $names[$i]).Trim() }
                throw ('Missing ' + $missing.Count + ' of ' + $partCount + ' parts of "' + $origName + '": part ' + ($missing -join ', ') + "`r`n(" + ($names -join ', ') + ')' + "`r`nStill needed: " + ($still -join ', '))
            }
            $manifest = $null
            for ($k = 1; $k -le $partCount -and -not $manifest; $k++) {
                $me = $use[$k].Zip.GetEntry($script:ZsManifestName)
                if ($me) { $manifest = Read-ZsJsonEntry $me }
            }
            if (-not $manifest) { throw 'The manifest (_zipsplitter_manifest.json) was not found in any part.' }
            if ([int]$manifest.version -gt 1) { $warnings.Add('Parts were made by a newer AgentParcel (manifest version ' + $manifest.version + ').') }

            $script:ZsJoinIndex = New-Object 'System.Collections.Generic.Dictionary[string,object]' ([System.StringComparer]::Ordinal)
            for ($k = 1; $k -le $partCount; $k++) {
                foreach ($en in $use[$k].Zip.Entries) {
                    if (-not $script:ZsJoinIndex.ContainsKey($en.FullName)) { $script:ZsJoinIndex[$en.FullName] = $en }
                }
            }
            $script:ZsJoinByArchive = @{}
            $depthOf = @{}
            foreach ($a in @($manifest.archives)) { $depthOf[[int]$a.id] = [int]$a.depth }
            $total = 0.0
            foreach ($rec in @($manifest.entries)) {
                $aid = [int]$rec.archive
                if (-not $script:ZsJoinByArchive.ContainsKey($aid)) { $script:ZsJoinByArchive[$aid] = [System.Collections.Generic.List[object]]::new() }
                $script:ZsJoinByArchive[$aid].Add($rec)
                if ($rec.type -eq 'file') { $d = 0; if ($depthOf.ContainsKey($aid)) { $d = $depthOf[$aid] }; $total += [double]$rec.size * (1 + $d) }
            }
            $script:ZsTotalWork = [Math]::Max(1.0, $total)

            $outPath = Get-ZsJoinOutputPath $OutputDir $partsDir $origName
            $tmpOut = Join-Path ([System.IO.Path]::GetDirectoryName($outPath)) ('~zs_rebuild_' + [guid]::NewGuid().ToString('N') + '.tmp')
            $script:ZsJoinVerified = 0
            $script:ZsJoinInnerZips = 0
            $fs = New-Object System.IO.FileStream($tmpOut, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::ReadWrite)
            $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create, $false)
            try { Write-ZsJoinArchive 0 $zip } finally { $zip.Dispose(); $fs.Dispose() }
            Move-Item -LiteralPath $tmpOut -Destination $outPath
            $tmpOut = $null
            $script:ZsDoneWork = $script:ZsTotalWork
            Report-ZsProgress 'Done.'
            return (New-Object PSObject -Property @{ OutputPath = $outPath; Mode = 'manifest'; PartCount = $partCount; Verified = $script:ZsJoinVerified; InnerZips = $script:ZsJoinInnerZips; Entries = @($manifest.entries).Count; Joined = 0; Warnings = $warnings.ToArray(); Size = (Get-Item -LiteralPath $outPath).Length })
        }

        # ================= legacy mode (parts made before manifests existed) =================
        $warnings.Add('These parts were made by an older AgentParcel (no manifest): files cannot be verified, and inner zips that were unpacked stay as folders (they cannot be turned back into zips).')
        $numbered = @($parts | Where-Object { $_.Info } | Sort-Object { $_.Info.Number })
        if ($numbered.Count -gt 0) {
            $nums = @{}; foreach ($p in $numbered) { $nums[$p.Info.Number] = $true }
            $maxN = $numbered[$numbered.Count - 1].Info.Number
            $missing = @(); for ($k = 1; $k -le $maxN; $k++) { if (-not $nums.ContainsKey($k)) { $missing += $k } }
            if ($missing.Count -gt 0) { throw ('Missing part(s): ' + ($missing -join ', ') + ' (found up to part ' + $maxN + '; for old-style parts a missing LAST part cannot be detected).') }
            $warnings.Add('Old-style parts carry no part count, so a missing last part (after part ' + $maxN + ') cannot be detected.')
            $ordered = @($numbered) + @($parts | Where-Object { -not $_.Info })
            $baseName = $numbered[0].Info.Base
        } else { $ordered = @($parts); $baseName = [System.IO.Path]::GetFileNameWithoutExtension($parts[0].Path) }

        $index = New-Object 'System.Collections.Generic.Dictionary[string,object]' ([System.StringComparer]::Ordinal)
        $order = New-Object System.Collections.Generic.List[string]
        $total = 0.0
        foreach ($p in $ordered) {
            foreach ($en in $p.Zip.Entries) {
                if (-not $index.ContainsKey($en.FullName)) { $index[$en.FullName] = $en; $order.Add($en.FullName); $total += $en.Length }
            }
        }
        $script:ZsTotalWork = [Math]::Max(1.0, $total)
        $pieceRx = New-Object System.Text.RegularExpressions.Regex('^(?<f>.+)\.(?<n>\d{3,})$')
        $outPath = Get-ZsJoinOutputPath $OutputDir $partsDir ($baseName + '.zip')
        $tmpOut = Join-Path ([System.IO.Path]::GetDirectoryName($outPath)) ('~zs_rebuild_' + [guid]::NewGuid().ToString('N') + '.tmp')
        $joined = 0
        $count = 0
        $fs = New-Object System.IO.FileStream($tmpOut, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::ReadWrite)
        $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create, $false)
        try {
            foreach ($nm in $order) {
                if ($nm.EndsWith('.REJOIN.txt')) {
                    $fbase = $nm.Substring(0, $nm.Length - 11)
                    $isNote = $false
                    foreach ($w in 3, 4, 5, 6) { if ($index.ContainsKey($fbase + '.' + '1'.PadLeft($w, '0'))) { $isNote = $true } }
                    if ($isNote) { continue }
                }
                $m = $pieceRx.Match($nm)
                if ($m.Success -and $index.ContainsKey($m.Groups['f'].Value + '.REJOIN.txt')) {
                    if ([int]$m.Groups['n'].Value -ne 1) { continue }
                    $fname = $m.Groups['f'].Value
                    $w = $m.Groups['n'].Value.Length
                    Report-ZsProgress ('Re-joining ' + $fname)
                    $e = $zip.CreateEntry($fname, [System.IO.Compression.CompressionLevel]::Optimal)
                    Set-ZsEntryTime $e $index[$nm]
                    $dst = $e.Open()
                    try {
                        $k = 1
                        while ($true) {
                            $pn = $fname + '.' + ([string]$k).PadLeft($w, '0')
                            if (-not $index.ContainsKey($pn)) { break }
                            $s = $index[$pn].Open()
                            try { Copy-ZsStream $s $dst $null } finally { $s.Dispose() }
                            $k++
                        }
                    } finally { $dst.Dispose() }
                    $joined++; $count++
                    continue
                }
                $src = $index[$nm]
                if ($nm.EndsWith('/') -or $nm.EndsWith('\')) { $e = $zip.CreateEntry($nm); Set-ZsEntryTime $e $src; $count++; continue }
                $e = $zip.CreateEntry($nm, [System.IO.Compression.CompressionLevel]::Optimal)
                Set-ZsEntryTime $e $src
                $dst = $e.Open(); $s = $src.Open()
                try { Copy-ZsStream $s $dst $null } finally { $s.Dispose(); $dst.Dispose() }
                $count++
            }
        } finally { $zip.Dispose(); $fs.Dispose() }
        Move-Item -LiteralPath $tmpOut -Destination $outPath
        $tmpOut = $null
        $script:ZsDoneWork = $script:ZsTotalWork
        Report-ZsProgress 'Done.'
        return (New-Object PSObject -Property @{ OutputPath = $outPath; Mode = 'legacy'; PartCount = $ordered.Count; Verified = 0; InnerZips = 0; Entries = $count; Joined = $joined; Warnings = $warnings.ToArray(); Size = (Get-Item -LiteralPath $outPath).Length })
    }
    finally {
        foreach ($z in $opened) { try { $z.Dispose() } catch { } }
        if ($tmpOut -and (Test-Path -LiteralPath $tmpOut)) { Remove-Item -LiteralPath $tmpOut -Force -ErrorAction SilentlyContinue }
        if (Test-Path -LiteralPath $script:ZsTempDir) { Remove-Item -LiteralPath $script:ZsTempDir -Recurse -Force -ErrorAction SilentlyContinue }
    }
}

function Format-ZsJoinSummary($Result) {
    $sb = New-Object System.Text.StringBuilder
    if ($Result.Mode -eq 'bytes') { [void]$sb.AppendLine('Rebuilt file:') } else { [void]$sb.AppendLine('Rebuilt zip:') }
    [void]$sb.AppendLine('  ' + $Result.OutputPath + ('  ({0:N2} MB)' -f ($Result.Size / 1MB)))
    [void]$sb.AppendLine('From ' + $Result.PartCount + ' part(s), ' + $Result.Entries + ' entries.')
    if ($Result.Mode -eq 'bytes') {
        [void]$sb.AppendLine('SHA-256 of the rebuilt file matches the manifest.')
    } elseif ($Result.Mode -eq 'manifest') {
        [void]$sb.AppendLine('All ' + $Result.Verified + ' files verified (size + SHA-256 match the original).')
        if ($Result.InnerZips -gt 0) { [void]$sb.AppendLine('Re-created ' + $Result.InnerZips + ' inner zip(s).') }
    } elseif ($Result.Joined -gt 0) {
        [void]$sb.AppendLine('Re-joined ' + $Result.Joined + ' file(s) from .001/.002 pieces.')
    }
    foreach ($w in $Result.Warnings) { [void]$sb.AppendLine(''); [void]$sb.AppendLine('NOTE: ' + $w) }
    return $sb.ToString()
}

