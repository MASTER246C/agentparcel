<#
  AgentParcel.ps1  (v3)  -  split a .zip into smaller standalone .zip parts, and rebuild it again.

  GUI:  double-click AgentParcel.bat, or drag a .zip (to split) or the parts / their folder
        (to rebuild) onto AgentParcel.bat or onto the window.
  CLI:  split:    powershell -ExecutionPolicy Bypass -File AgentParcel.ps1 -NoGui [-LimitMB 19.5] [-NoUnpackInner] [-NoIncludeApps] [-OutputDir D:\out] "C:\path\file.zip"
        rebuild:  powershell -ExecutionPolicy Bypass -File AgentParcel.ps1 -Join "C:\path\file_split" [-OutputDir D:\out]
                  (-Join accepts a folder of parts, one part (siblings are found automatically) or several parts)

  Split: every part is <= LimitMB (default 19.5 MB = 19.5 * 1024 * 1024 bytes) and opens on its own.
  Zips inside the zip (any depth) are unpacked into folders named after them (default; -NoUnpackInner
  turns it off). A single file too big even after compression is cut into raw pieces <file>.001, .002...
  Every part carries _zipsplitter_part.json; the first and last parts carry _zipsplitter_manifest.json
  (format documented in README.txt) so Join can rebuild the original zip, inner zips included, and
  verify every file with SHA-256.
  By default the split also writes AgentParcel-apps.zip (this program for Windows, Mac and Linux) next
  to the parts so the recipient can rebuild; -NoIncludeApps turns it off.
  Compatible with Windows PowerShell 5.1 and PowerShell 7+.
#>
[CmdletBinding()]
