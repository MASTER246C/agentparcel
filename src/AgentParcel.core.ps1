    [Parameter(Position = 0, ValueFromRemainingArguments = $true)]
    [string[]]$Path,
    [double]$LimitMB = 19.5,
    [string]$OutputDir,
    [switch]$NoUnpackInner,
    [string[]]$Join,
    [string[]]$Verify,
    [switch]$SplitBytes,
    [switch]$IncludeApps,
    [switch]$NoIncludeApps,
    [switch]$NoGui
)

