function Get-ZsPayloadFiles {
    $b64 = ($script:ZsPayload -replace '\s', '')
    if (-not $b64) { return $null }
    $bytes = [Convert]::FromBase64String($b64)
    $ms = New-Object System.IO.MemoryStream(,$bytes)
    $ds = New-Object System.IO.Compression.DeflateStream($ms, [System.IO.Compression.CompressionMode]::Decompress)
    $sr = New-Object System.IO.StreamReader($ds, [System.Text.Encoding]::UTF8)
    try { $txt = $sr.ReadToEnd() } finally { $sr.Dispose() }
    $obj = ConvertFrom-ZsJson $txt
    return ,(Get-ZsProp $obj 'files')
}

function Get-ZsIconBytes([string]$Key) {
    # icons travel in the payload as base64 text (icon-*.b64), so a release copy works standalone
    $files = $null
    try { $files = Get-ZsPayloadFiles } catch { return $null }
    if (-not $files) { return $null }
    $t = Get-ZsProp $files $Key
    if (-not $t) { return $null }
    return ,([Convert]::FromBase64String([string]$t))
}

function Set-ZsPayloadText([string]$Core, [string]$B64, [string]$NL, [string]$Lang) {
    # Same algorithm as fill_payload() in agentparcel.py and build.py (output must be identical).
    $begin = '#==ZS-PAYLOAD-BEGIN==' + $NL
    $end = '#==ZS-PAYLOAD-END=='
    $i = $Core.IndexOf($begin, [StringComparison]::Ordinal)
    $j = $Core.IndexOf($end, [Math]::Max($i, 0), [StringComparison]::Ordinal)
    if ($i -lt 0 -or $j -lt $i) { throw 'payload markers not found' }
    $lines = New-Object System.Collections.Generic.List[string]
    for ($k = 0; $k -lt $B64.Length; $k += 76) { $lines.Add($B64.Substring($k, [Math]::Min(76, $B64.Length - $k))) }
    $body = [string]::Join($NL, $lines.ToArray())
    if ($Lang -eq 'ps') { $block = "`$script:ZsPayload = @'" + $NL + $body + $NL + "'@" + $NL }
    else { $block = 'PAYLOAD = """' + $NL + $body + $NL + '"""' + $NL }
    return $Core.Substring(0, $i + $begin.Length) + $block + $Core.Substring($j)
}

function Set-ZsZipUnixMadeBy([string]$Path) {
    # Marks every central-directory record as "made by Unix" so macOS/Linux honour the
    # permission bits (exec flag) stored in the external attributes.
    $b = [System.IO.File]::ReadAllBytes($Path)
    $eocd = -1
    for ($i = $b.Length - 22; $i -ge [Math]::Max(0, $b.Length - 65557); $i--) {
        if ($b[$i] -eq 0x50 -and $b[$i + 1] -eq 0x4b -and $b[$i + 2] -eq 0x05 -and $b[$i + 3] -eq 0x06) { $eocd = $i; break }
    }
    if ($eocd -lt 0) { return }
    $count = [BitConverter]::ToUInt16($b, $eocd + 10)
    $pos = [long][BitConverter]::ToUInt32($b, $eocd + 16)
    for ($n = 0; $n -lt $count; $n++) {
        if ($pos + 46 -gt $b.Length -or [BitConverter]::ToUInt32($b, [int]$pos) -ne 0x02014b50) { return }
        $b[[int]$pos + 4] = 20
        $b[[int]$pos + 5] = 3
        $pos += 46 + [BitConverter]::ToUInt16($b, [int]$pos + 28) + [BitConverter]::ToUInt16($b, [int]$pos + 30) + [BitConverter]::ToUInt16($b, [int]$pos + 32)
    }
    [System.IO.File]::WriteAllBytes($Path, $b)
}

function Write-ZsAppsBundle([string]$OutDir, [long]$LimitBytes) {
    $files = $null
    try { $files = Get-ZsPayloadFiles } catch { $files = $null }
    if (-not $files) {
        return (New-Object PSObject -Property @{ Path = $null; Size = 0; Note = 'Apps bundle not included: this copy of AgentParcel has no embedded apps (development copy).' })
    }
    $b64 = ($script:ZsPayload -replace '\s', '')
    $ps = Set-ZsPayloadText (Get-ZsProp $files 'AgentParcel.ps1') $b64 "`r`n" 'ps'
    $py = Set-ZsPayloadText (Get-ZsProp $files 'agentparcel.py') $b64 "`n" 'py'
    $f644 = -2119958528    # (0100644 << 16) as Int32
    $f755 = -2115174400    # (0100755 << 16) as Int32
    $dir = 1106051088      # (040755 << 16) | 0x10
    $list = @(
        @('HOW TO REBUILD.txt', (Get-ZsProp $files 'HOW TO REBUILD.txt'), $f644),
        @('LICENSE.txt', (Get-ZsProp $files 'LICENSE.txt'), $f644),
        @('Windows/AgentParcel.ps1', $ps, $f644),
        @('Windows/AgentParcel.bat', (Get-ZsProp $files 'AgentParcel.bat'), $f644),
        @('Windows/README.txt', (Get-ZsProp $files 'README-windows.txt'), $f644),
        @('Windows/Install-Python-for-AgentParcel.bat', (Get-ZsProp $files 'Install-Python-for-AgentParcel.bat'), $f644),
        @('Windows/AgentParcel.ico', [byte[]][Convert]::FromBase64String([string](Get-ZsProp $files 'icon-AgentParcel.ico.b64')), $f644),
        @('mac/agentparcel.py', $py, $f755),
        @('mac/AgentParcel.command', (Get-ZsProp $files 'AgentParcel.command'), $f755),
        @('mac/README.txt', (Get-ZsProp $files 'README-mac-linux.txt'), $f644),
        @('linux/agentparcel.py', $py, $f755),
        @('linux/agentparcel.sh', (Get-ZsProp $files 'agentparcel.sh'), $f755),
        @('linux/agentparcel.desktop', (Get-ZsProp $files 'agentparcel.desktop'), $f644),
        @('linux/agentparcel.png', [byte[]][Convert]::FromBase64String([string](Get-ZsProp $files 'icon-agentparcel-64.png.b64')), $f644),
        @('linux/README.txt', (Get-ZsProp $files 'README-mac-linux.txt'), $f644),
        @('mcp/agentparcel_mcp.py', (Get-ZsProp $files 'agentparcel_mcp.py'), $f755),
        @('mcp/agentparcel.py', $py, $f755),
        @('mcp/README.txt', (Get-ZsProp $files 'README-mcp.txt'), $f644),
        @($script:ZsAppsMarker, (ConvertTo-ZsJsonObject @('format', 'zipsplitter-apps', 'version', $script:ZsVersion)), $f644)
    )
    $path = Get-ZsUniquePath (Join-Path $OutDir $script:ZsAppsName)
    $fs = New-Object System.IO.FileStream($path, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::ReadWrite)
    $zip = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create, $false)
    try {
        foreach ($d in @('Windows/', 'mac/', 'linux/', 'mcp/')) {
            $e = $zip.CreateEntry($d)
            try { $e.ExternalAttributes = $dir } catch { }
        }
        foreach ($f in $list) {
            $e = $zip.CreateEntry([string]$f[0], [System.IO.Compression.CompressionLevel]::Optimal)
            try { $e.ExternalAttributes = [int]$f[2] } catch { }
            if ($f[1] -is [byte[]]) { $bytes = [byte[]]$f[1] } else { $bytes = [System.Text.Encoding]::UTF8.GetBytes([string]$f[1]) }
            $dst = $e.Open()
            try { $dst.Write($bytes, 0, $bytes.Length) } finally { $dst.Dispose() }
        }
    }
    finally { $zip.Dispose(); $fs.Dispose() }
    Set-ZsZipUnixMadeBy $path
    $size = (Get-Item -LiteralPath $path).Length
    if ($size -gt $LimitBytes) {
        Remove-Item -LiteralPath $path -Force
        return (New-Object PSObject -Property @{ Path = $null; Size = 0; Note = ('Apps bundle not included: it is {0:N2} MB, bigger than the size limit.' -f ($size / 1MB)) })
    }
    return (New-Object PSObject -Property @{ Path = $path; Size = $size; Note = $null })
}

