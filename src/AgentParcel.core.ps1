function Set-ZsEntryTimeFromString($NewEntry, $Value) {
    if ($null -eq $Value -or [string]$Value -eq '') { return }
    try {
        if ($Value -is [DateTime]) { $dt = [DateTime]::SpecifyKind($Value, [DateTimeKind]::Unspecified) }
        else { $dt = [DateTime]::ParseExact([string]$Value, 'yyyy-MM-dd HH:mm:ss', [System.Globalization.CultureInfo]::InvariantCulture) }
        $NewEntry.LastWriteTime = New-Object System.DateTimeOffset($dt)
    } catch { }
}

function Get-ZsUniquePath([string]$Wanted) {
    if (-not (Test-Path -LiteralPath $Wanted)) { return $Wanted }
    $dir = [System.IO.Path]::GetDirectoryName($Wanted)
    $stem = [System.IO.Path]::GetFileNameWithoutExtension($Wanted)
    $ext = [System.IO.Path]::GetExtension($Wanted)
    $n = 2
    while ($true) {
        $cand = Join-Path $dir ($stem + ' (' + $n + ')' + $ext)
        if (-not (Test-Path -LiteralPath $cand)) { return $cand }
        $n++
    }
}

