        'github-release' { return '1,900,000,000 bytes, under 2 GB. Limits can change.' }
        default { return 'Custom size in MB. Default 19.5.' }
    }
}

function Invoke-ZsRegeneratePlain {
    param([string]$Original, [string[]]$InputPaths)
    $manifestPath = Find-ZsByteManifest $InputPaths
    if (-not $manifestPath) { throw 'Re-send from this window works for a plain byte-split folder. For a zip set, use the Python app.' }
    $manifest = Get-Content -Raw -LiteralPath $manifestPath | ConvertFrom-Json
    $propNames = @($manifest.PSObject.Properties.Name)
    if ($propNames -contains 'encryption' -or $propNames -contains 'compression') {
        throw 'This set uses compression or encryption. Re-send those parts with the Python app or regenerate_parts. This window only rewrites plain byte parts.'
    }
    $origItem = Get-Item -LiteralPath $Original
    if ($origItem.Name -ne [string](Get-ZsProp $manifest 'originalName')) { throw 'The original file name does not match this part set.' }
    if ((Get-ZsSha256File $Original) -ne [string](Get-ZsProp $manifest 'sha256')) { throw 'The original file does not match this part set (SHA-256).' }
    if ($origItem.Length -ne [long](Get-ZsProp $manifest 'originalSize')) { throw 'The original file size does not match this part set.' }
    $report = Invoke-ZsVerifyBytes $manifestPath
    $targets = New-Object System.Collections.Generic.List[int]
    foreach ($n in @($report.Missing)) { if ($null -ne $n -and "$n" -ne '') { [void]$targets.Add([int]$n) } }
    foreach ($c in @($report.Corrupt)) {
        if ($c -and $null -ne $c.Part -and -not $targets.Contains([int]$c.Part)) { [void]$targets.Add([int]$c.Part) }
    }
    $folder = [System.IO.Path]::GetDirectoryName($manifestPath)
    if ($targets.Count -eq 0) {
        return (New-Object PSObject -Property @{ Ok = $true; Message = 'Nothing to regenerate. All parts match the manifest.'; OutputDir = $folder })
    }
    $by = @{}
    foreach ($p in @($manifest.parts)) { $by[[int]$p.part] = $p }
    $src = [System.IO.File]::OpenRead($Original)
    $done = New-Object System.Collections.Generic.List[string]
    try {
        foreach ($number in $targets) {
            $part = $by[[int]$number]
            if (-not $part) { throw ('Part ' + $number + ' is not in the manifest.') }
            $src.Position = [long]$part.offset
            $left = [long]$part.size
            $dest = Join-Path $folder ([string]$part.name)
            $tmp = $dest + '.new'
            $out = [System.IO.File]::Open($tmp, [System.IO.FileMode]::Create)
            $buf = New-Object byte[] 1048576
            try {
                while ($left -gt 0) {
                    $want = $buf.Length
                    if ($want -gt $left) { $want = [int]$left }
                    $nread = $src.Read($buf, 0, $want)
                    if ($nread -le 0) { throw ('The original file is shorter than part ' + $number + ' needs.') }
                    $out.Write($buf, 0, $nread)
                    $left -= $nread
                }
            } finally { $out.Dispose() }
            if (Test-Path -LiteralPath $dest) { Remove-Item -LiteralPath $dest -Force }
            Move-Item -LiteralPath $tmp -Destination $dest
            [void]$done.Add('part ' + $number + ' (' + $part.name + ')')
        }
    } finally { $src.Dispose() }
    $after = Invoke-ZsVerifyBytes $manifestPath
    $msg = 'Regenerated ' + ($done -join ', ') + '.'
    if ($after.Ok) { $msg += "`nAll parts are now present and match the manifest." } else { $msg += "`n" + $after.Message }
    return (New-Object PSObject -Property @{ Ok = [bool]$after.Ok; Message = $msg; OutputDir = $folder })
}

function Invoke-ZsVerifyZip([string[]]$InputPaths) {
    $files = @(Find-ZsPartSet $InputPaths)
    if ($files.Count -eq 0) { throw 'No parts found.' }
    $opened = [System.Collections.Generic.List[object]]::new()
    try {
        $parts = [System.Collections.Generic.List[object]]::new()
        $unreadable = [System.Collections.Generic.List[object]]::new()
        foreach ($path in $files) {
            Report-ZsProgress ('Opening ' + [System.IO.Path]::GetFileName($path))
            $zf = $null
            try { $zf = [System.IO.Compression.ZipFile]::OpenRead($path) }
            catch {
                $info = Get-ZsPartInfo ([System.IO.Path]::GetFileName($path))
                $number = $null
                if ($info) { $number = $info.Number }
                $unreadable.Add((New-Object PSObject -Property @{ Part = $number; Name = [System.IO.Path]::GetFileName($path); Reason = 'not a readable zip' }))
                continue
            }
            if ($zf.GetEntry($script:ZsAppsMarker)) { $zf.Dispose(); continue }
            $opened.Add($zf)
            $stub = $null
            $stubEntry = $zf.GetEntry($script:ZsStubName)
            if ($stubEntry) { try { $stub = Read-ZsJsonEntry $stubEntry } catch { $stub = $null } }
            $parts.Add((New-Object PSObject -Property @{ Path = $path; Zip = $zf; Stub = $stub; Info = (Get-ZsPartInfo ([System.IO.Path]::GetFileName($path))) }))
        }
        if ($parts.Count -eq 0) {
            if ($unreadable.Count -gt 0) { return (New-ZsVerifyReport 'zipsplitter-manifest' '' 0 @() @() $unreadable.ToArray() @()) }
            throw 'No parts found (only the AgentParcel-apps.zip bundle).'
        }
        $labelled = @($parts | Where-Object { $_.Stub })
        if ($labelled.Count -eq 0) {
            $present = @($parts | Where-Object { $_.Info } | ForEach-Object { $_.Info.Number } | Sort-Object)
            $report = New-ZsVerifyReport 'legacy' '' ([int](($present | Measure-Object -Maximum).Maximum)) @() @() $unreadable.ToArray() $present
            if ($report.Ok) { $report.Message = 'Present part(s): ' + ($present -join ', ') + '. These parts have no manifest, so checksums cannot be checked.' }
            return $report
        }
        $first = $labelled[0].Stub
        $setId = [string](Get-ZsProp $first 'setId')
        $partCount = [int](Get-ZsProp $first 'partCount')
        $original = [string](Get-ZsProp $first 'originalName')
        $use = @{}
        foreach ($p in $parts) {
            if (-not $p.Stub) { continue }
            if ([string](Get-ZsProp $p.Stub 'setId') -ne $setId) { continue }
            $number = [int](Get-ZsProp $p.Stub 'part')
            if ($number -gt 0 -and -not $use.ContainsKey($number)) { $use[$number] = $p }
        }
        $stem = [System.IO.Path]::GetFileNameWithoutExtension($original)
        $width = [Math]::Max(2, ([string]$partCount).Length)
        $missing = @()
        $missingNames = @()
        for ($k = 1; $k -le $partCount; $k++) {
            if (-not $use.ContainsKey($k)) {
                $missing += $k
                $missingNames += ($stem + '_part' + ([string]$k).PadLeft($width, '0') + '.zip')
            }
        }
        $present = @($use.Keys | Sort-Object)
        $manifest = $null
        foreach ($number in $present) {
            $entry = $use[$number].Zip.GetEntry($script:ZsManifestName)
            if ($entry) { $manifest = Read-ZsJsonEntry $entry; break }
        }
        $corrupt = [System.Collections.Generic.List[object]]::new()
        foreach ($item in $unreadable) { $corrupt.Add($item) }
        if (-not $manifest) {
            $corrupt.Add((New-Object PSObject -Property @{ Part = $null; Name = $script:ZsManifestName; Reason = 'manifest was not found in any present part' }))
        } else {
            $index = @{}
            $partOf = @{}
            foreach ($number in $present) {
                foreach ($zi in $use[$number].Zip.Entries) {
                    if (-not $index.ContainsKey($zi.FullName)) { $index[$zi.FullName] = $zi; $partOf[$zi.FullName] = $number }
                }
            }
            $entries = Get-ZsItems $manifest 'entries'
            foreach ($rec in $entries) {
                if ([string](Get-ZsProp $rec 'type') -ne 'file') { continue }
                $stored = [string](Get-ZsProp $rec 'stored')
                Report-ZsProgress ('Checking ' + $stored)
                $sources = @()
                if ($index.ContainsKey($stored)) { $sources = @($index[$stored]) }
                else {
                    foreach ($w in 3, 4, 5, 6) {
                        $firstName = $stored + '.' + ('1'.PadLeft($w, '0'))
                        if ($index.ContainsKey($firstName)) {
                            $k = 1
                            while ($index.ContainsKey($stored + '.' + ([string]$k).PadLeft($w, '0'))) {
                                $sources += $index[$stored + '.' + ([string]$k).PadLeft($w, '0')]
                                $k++
                            }
                            break
                        }
                    }
                }
                if ($sources.Count -eq 0) {
                    if ($missing.Count -eq 0) {
                        $corrupt.Add((New-Object PSObject -Property @{ Part = $null; Name = $stored; Reason = 'file data is missing from the parts' }))
                    }
                    continue
                }
                $hasher = New-ZsHasher
                $total = [long]0
                $holder = $partOf[$sources[0].FullName]
                foreach ($zi in $sources) {
                    $stream = $zi.Open()
                    try { Copy-ZsStream $stream $null $hasher; $total += $zi.Length } finally { $stream.Dispose() }
                }
                $digest = Complete-ZsHasher $hasher
                $expectSize = [long](Get-ZsProp $rec 'size')
                $expectHash = ([string](Get-ZsProp $rec 'sha256')).ToLowerInvariant()
                if ($total -ne $expectSize -or $digest -ne $expectHash) {
                    $cname = $stored
                    if ($use.ContainsKey([int]$holder)) { $cname = [System.IO.Path]::GetFileName($use[[int]$holder].Path) }
                    $corrupt.Add((New-Object PSObject -Property @{ Part = $holder; Name = $cname; Reason = ('SHA-256 or size does not match the manifest for ' + $stored) }))
                }
            }
        }
        $side = Join-Path ([System.IO.Path]::GetDirectoryName($parts[0].Path)) $script:ZsZipsetManifest
        if (Test-Path -LiteralPath $side -PathType Leaf) {
            $sideObj = ConvertFrom-ZsJson ([System.IO.File]::ReadAllText($side))
            foreach ($rec in (Get-ZsItems $sideObj 'parts')) {
                $name = [string](Get-ZsProp $rec 'name')
                Report-ZsProgress ('Checksum ' + $name)
                $path = Join-Path ([System.IO.Path]::GetDirectoryName($parts[0].Path)) $name
                if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { continue }
                $digest = Get-ZsSha256File $path
                $size = [long](Get-Item -LiteralPath $path).Length
                if ($size -ne [long](Get-ZsProp $rec 'size') -or $digest -ne ([string](Get-ZsProp $rec 'sha256')).ToLowerInvariant()) {
                    $corrupt.Add((New-Object PSObject -Property @{ Part = (Get-ZsProp $rec 'part'); Name = $name; Reason = 'part file SHA-256 or size does not match _agentparcel_zipset.json' }))
                }
            }
        }
        return (New-ZsVerifyReport 'zipsplitter-manifest' $original $partCount $missing $missingNames $corrupt.ToArray() $present)
    } finally {
        foreach ($z in $opened) { try { $z.Dispose() } catch { } }
    }
}

function Invoke-ZsVerify {
    param([string[]]$InputPaths, [scriptblock]$OnProgress)
    $script:ZsProgress = $OnProgress
    $script:ZsDoneWork = 0.0
    $script:ZsLastPct = -1
    $script:ZsTotalWork = 1.0
    $manifest = Find-ZsByteManifest $InputPaths
    if ($manifest) { return (Invoke-ZsVerifyBytes $manifest) }
    return (Invoke-ZsVerifyZip $InputPaths)
}

function Invoke-ByteRebuild {
    param([string]$ManifestPath, [string]$OutputDir, [scriptblock]$OnProgress)
    $script:ZsProgress = $OnProgress
    $script:ZsDoneWork = 0.0
    $script:ZsLastPct = -1
    $bad = Invoke-ZsVerifyBytes $ManifestPath
    if (-not $bad.Ok) { throw $bad.Message }
    $folder = [System.IO.Path]::GetDirectoryName($ManifestPath)
    $manifest = ConvertFrom-ZsJson ([System.IO.File]::ReadAllText($ManifestPath))
    $original = [string](Get-ZsProp $manifest 'originalName')
    if ($OutputDir) {
        if (-not (Test-Path -LiteralPath $OutputDir)) { [void](New-Item -ItemType Directory -Path $OutputDir) }
        $dest = Get-ZsUniquePath (Join-Path ((Resolve-Path -LiteralPath $OutputDir).ProviderPath) $original)
    } else {
        $dest = Get-ZsUniquePath (Join-Path $folder $original)
    }
    $tmp = $dest + '.partial'
    $script:ZsTotalWork = [Math]::Max(1.0, [double](Get-ZsProp $manifest 'originalSize'))
    $script:ZsDoneWork = 0.0
    $whole = New-ZsHasher
    try {
        $out = [System.IO.File]::Open($tmp, [System.IO.FileMode]::CreateNew)
        try {
            foreach ($part in (Get-ZsItems $manifest 'parts')) {
                Report-ZsProgress ('Rebuilding part ' + (Get-ZsProp $part 'part'))
                $path = Join-Path $folder ([string](Get-ZsProp $part 'name'))
                $inp = [System.IO.File]::OpenRead($path)
                try { Copy-ZsStream $inp $out $whole } finally { $inp.Dispose() }
            }
        } finally { $out.Dispose() }
        $digest = Complete-ZsHasher $whole
        if ($digest -ne ([string](Get-ZsProp $manifest 'sha256')).ToLowerInvariant() -or (Get-Item -LiteralPath $tmp).Length -ne [long](Get-ZsProp $manifest 'originalSize')) {
            throw 'Rebuilt file does not match the manifest SHA-256.'
        }
        Move-Item -LiteralPath $tmp -Destination $dest
        $tmp = $null
    } catch {
        if ($tmp -and (Test-Path -LiteralPath $tmp)) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
        throw
    }
    Report-ZsProgress 'Done.'
    $count = (Get-ZsItems $manifest 'parts').Count
    return (New-Object PSObject -Property @{
        OutputPath = $dest; Mode = 'bytes'; PartCount = $count; Verified = 1; InnerZips = 0
        Entries = 1; Joined = 0; Warnings = @(); Size = (Get-Item -LiteralPath $dest).Length
    })
}

function Invoke-Rebuild {
    param([string[]]$InputPaths, [string]$OutputDir, [scriptblock]$OnProgress)
    $manifest = Find-ZsByteManifest $InputPaths
    if ($manifest) { return (Invoke-ByteRebuild -ManifestPath $manifest -OutputDir $OutputDir -OnProgress $OnProgress) }
    return (Invoke-ZipJoin -InputPaths $InputPaths -OutputDir $OutputDir -OnProgress $OnProgress)
}


function Invoke-ZipSplit {
    param(
        [Parameter(Mandatory = $true)][string]$SourcePath,
        [string]$OutputDir,
        [long]$LimitBytes = [long](19.5 * 1024 * 1024),
        [bool]$UnpackInner = $true,
        [bool]$IncludeApps = $true,
        [scriptblock]$OnProgress
    )
    $SourcePath = (Resolve-Path -LiteralPath $SourcePath).ProviderPath
    $srcInfo = Get-Item -LiteralPath $SourcePath
    $base = [System.IO.Path]::GetFileNameWithoutExtension($srcInfo.Name)
    if (-not $OutputDir) {
        $OutputDir = Join-Path $srcInfo.DirectoryName ($base + '_split')
        $n = 2
        while ((Test-Path -LiteralPath $OutputDir) -and @(Get-ChildItem -LiteralPath $OutputDir -Force).Count -gt 0) {
            $OutputDir = Join-Path $srcInfo.DirectoryName ($base + '_split (' + $n + ')')
            $n++
        }
    }
    $createdDir = -not (Test-Path -LiteralPath $OutputDir)
    if ($createdDir) { [void](New-Item -ItemType Directory -Path $OutputDir) }
    $OutputDir = (Resolve-Path -LiteralPath $OutputDir).ProviderPath

    $script:ZsProgress = $OnProgress
    $script:ZsDoneWork = 0.0
    $script:ZsLastPct = -1

    $fixed = [long](22 + 56 + 20)                        # EOCD + zip64 EOCD + locator
    $stubReserve = [long]4096                            # room for _zipsplitter_part.json added at the end
    $budget = $LimitBytes - $fixed - 32768 - $stubReserve
    $chunkBudget = $LimitBytes - $fixed - 131072 - $stubReserve
    if ($budget -lt 65536) { throw 'Limit is too small (minimum is about 0.2 MB).' }

    $setId = [guid]::NewGuid().ToString('N')
    $tempParts = New-Object System.Collections.Generic.List[string]
    $splitFiles = [System.Collections.Generic.List[object]]::new()
    $script:ZsOpened = [System.Collections.Generic.List[object]]::new()
    $script:ZsUnpacked = New-Object System.Collections.Generic.List[string]
    $script:ZsUnpackFailed = New-Object System.Collections.Generic.List[string]
    $script:ZsMEntries = New-Object System.Collections.Generic.List[string]
    $script:ZsMArchives = New-Object System.Collections.Generic.List[string]
    $script:ZsArchiveCounter = 0
    $script:ZsTempDir = New-ZsTempDir
    $archive = $null
    try {
        $archive = [System.IO.Compression.ZipFile]::OpenRead($SourcePath)
        $total = 0.0
        foreach ($e in $archive.Entries) { $total += $e.Length }
        $script:ZsTotalWork = [Math]::Max(1.0, 2.0 * $total)

        # ---- Phase 1: measure + hash every entry (unpacking inner zips) ----
        $items = [System.Collections.Generic.List[object]]::new()
        $script:ZsMArchives.Add((ConvertTo-ZsJsonObject @('id', 0, 'parent', -1, 'depth', 0, 'entry', '', 'folder', '')))
        Add-ZsArchiveItems $archive '' $items $budget $UnpackInner 0 0

        # ---- Manifest (complete before any part is written) ----
        $mj = New-Object System.Text.StringBuilder
        [void]$mj.Append('{"format":"zipsplitter-manifest","version":1')
        [void]$mj.Append(',"setId":' + (ConvertTo-ZsJsonValue $setId))
        [void]$mj.Append(',"tool":' + (ConvertTo-ZsJsonValue $script:ZsToolName))
        [void]$mj.Append(',"created":' + (ConvertTo-ZsJsonValue ([DateTime]::Now.ToString('yyyy-MM-dd HH:mm:ss', [System.Globalization.CultureInfo]::InvariantCulture))))
        [void]$mj.Append(',"originalName":' + (ConvertTo-ZsJsonValue $srcInfo.Name))
        [void]$mj.Append(',"originalSize":' + [long]$srcInfo.Length)
        [void]$mj.Append(',"limitBytes":' + $LimitBytes)
        [void]$mj.Append(',"unpackInner":' + (ConvertTo-ZsJsonValue $UnpackInner))
        [void]$mj.Append(",`n""archives"":[`n" + ($script:ZsMArchives -join ",`n") + "`n]")
        [void]$mj.Append(",`n""entries"":[`n" + ($script:ZsMEntries -join ",`n") + "`n]}`n")
        $mBytes = [System.Text.Encoding]::UTF8.GetBytes($mj.ToString())
        $mCost = (Get-ZsDeflatedSizeOfBytes $mBytes $mBytes.Length) + (Get-ZsEntryOverhead $script:ZsManifestName)
        if ($mCost -gt $budget) { throw 'Too many files: the manifest alone is bigger than one part. Use a larger size limit.' }
        $mItem1 = New-Object PSObject -Property @{ Kind = 'blob'; Name = $script:ZsManifestName; Bytes = $mBytes; Cost = $mCost; Len = 0; IsManifest = $true; Entry = $null }
        $mItem2 = New-Object PSObject -Property @{ Kind = 'blob'; Name = $script:ZsManifestName; Bytes = $mBytes; Cost = $mCost; Len = 0; IsManifest = $true; Entry = $null }

        # ---- Phase 2: write the parts (manifest goes first and last) ----
        $pending = [System.Collections.Generic.List[object]]::new()
        $pending.Add($mItem1)
        foreach ($it in $items) { $pending.Add($it) }
        $pending.Add($mItem2)
        $partNo = 0
        while ($pending.Count -gt 0) {
            $next = $pending[0]
            if ($next.Kind -eq 'chunked') {
                $pending.RemoveAt(0)
                # ---- split one big entry into raw pieces, one piece per part ----
                $ratio = [double]$next.Comp / [Math]::Max(1.0, [double]$next.Len)
                if ($ratio -lt 0.05) { $ratio = 0.05 }
                $raw = [long][Math]::Floor($chunkBudget / $ratio * 0.97)
                $maxRaw = [long](64 * 1024 * 1024)
                if ($maxRaw -lt $chunkBudget) { $maxRaw = $chunkBudget }
                if ($raw -gt $maxRaw) { $raw = $maxRaw }
                if ($raw -lt 65536) { $raw = 65536 }
                $buf = New-Object byte[] ([int]($raw + 1))
                $filled = 0
                $eof = $false
                $pieceNo = 0
                $width = [Math]::Max(3, ([string][long][Math]::Ceiling($next.Len / [double]$raw * 1.5 + 1)).Length)
                $info = New-Object PSObject -Property @{ Name = $next.Name; Pieces = (New-Object System.Collections.Generic.List[string]); PartIndexes = (New-Object System.Collections.Generic.List[int]); PartNames = (New-Object System.Collections.Generic.List[string]); TextPart = $null; TextPartItems = $null }
                $src = $next.Entry.Open()
                try {
                    while ($true) {
                        while (-not $eof -and $filled -lt $buf.Length) {
                            $r = $src.Read($buf, $filled, $buf.Length - $filled)
                            if ($r -le 0) { $eof = $true } else { $filled += $r }
                        }
                        if ($filled -eq 0) { break }
                        $take = [int][Math]::Min([long]$filled, $raw)
                        while ($true) {
                            $pieceName = $next.Name + '.' + ([string]($pieceNo + 1)).PadLeft($width, '0')
                            $c = Get-ZsDeflatedSizeOfBytes $buf $take
                            if (($c + (Get-ZsEntryOverhead $pieceName)) -le $chunkBudget -or $take -le 65536) { break }
                            $take = [int][Math]::Floor($take * 0.9)
                            $raw = $take
                        }
                        $pieceNo++
                        $isLast = $eof -and ($take -eq $filled)
                        $partNo++
                        $tmp = Join-Path $OutputDir ('~zs_part' + $partNo + '.tmp')
                        $partItems = [System.Collections.Generic.List[object]]::new()
                        $partItems.Add((New-Object PSObject -Property @{ Kind = 'bytes'; Name = $pieceName; Entry = $next.Entry; Buffer = $buf; Count = $take }))
                        $info.Pieces.Add($pieceName)
                        $info.PartIndexes.Add($partNo)
                        if ($isLast) {
                            $partItems.Add((New-Object PSObject -Property @{ Kind = 'text'; Name = $next.Name + '.REJOIN.txt'; Text = '@@REJOIN@@' }))
                            $copy = New-Object byte[] $take
                            [Array]::Copy($buf, 0, $copy, 0, $take)
                            $partItems[0].Buffer = $copy
                            $info.TextPart = $tmp
                            $info.TextPartItems = $partItems
                        }
                        Report-ZsProgress ('Writing part ' + $partNo + ' (piece ' + $pieceNo + ' of ' + $next.Name + ')')
                        $size = Write-ZsPart $tmp $partItems
                        if ($size -gt $LimitBytes) { throw ('Internal error: piece part exceeded the limit (' + $size + ' bytes).') }
                        $tempParts.Add($tmp)
                        $script:ZsDoneWork += $take
                        $left = $filled - $take
                        if ($left -gt 0) { [Array]::Copy($buf, $take, $buf, 0, $left) }
                        $filled = $left
                        if ($isLast) { break }
                    }
                }
                finally { $src.Dispose() }
                $splitFiles.Add($info)
                continue
            }

            # ---- normal part: greedy fill ----
            $partItems = [System.Collections.Generic.List[object]]::new()
            $used = [long]0
            $hasManifest = $false
            while ($pending.Count -gt 0 -and $pending[0].Kind -ne 'chunked') {
                $cand = $pending[0]
                if ($cand.IsManifest -and $hasManifest) { $pending.RemoveAt(0); continue }   # never twice in one part
                if ($partItems.Count -gt 0 -and ($used + $cand.Cost) -gt $budget) { break }
                $used += $cand.Cost
                if ($cand.IsManifest) { $hasManifest = $true }
                $partItems.Add($cand)
                $pending.RemoveAt(0)
            }
            if ($partItems.Count -eq 0) { continue }
            $partNo++
            $tmp = Join-Path $OutputDir ('~zs_part' + $partNo + '.tmp')
            while ($true) {
                $before = $script:ZsDoneWork
                Report-ZsProgress ('Writing part ' + $partNo + ' (' + $partItems.Count + ' entries)')
                $size = Write-ZsPart $tmp $partItems
                if ($size -le ($LimitBytes - $stubReserve)) { break }
                # Estimate was off: move the last entry back and try again.
                $script:ZsDoneWork = $before
                Remove-Item -LiteralPath $tmp -Force
                $last = $partItems[$partItems.Count - 1]
                $partItems.RemoveAt($partItems.Count - 1)
                if ($partItems.Count -eq 0) {
                    if ($last.IsManifest) { throw 'Manifest does not fit in one part.' }
                    $last.Kind = 'chunked'
                }
                $pending.Insert(0, $last)
                if ($partItems.Count -eq 0) { break }
            }
            if ($partItems.Count -eq 0) { $partNo--; continue }
            $tempParts.Add($tmp)
        }
    }
    catch {
        foreach ($t in @($tempParts)) { if ($t -and (Test-Path -LiteralPath $t)) { Remove-Item -LiteralPath $t -Force -ErrorAction SilentlyContinue } }
        Remove-ZsOwned @() $OutputDir $createdDir
        throw
    }
    finally {
        foreach ($a in $script:ZsOpened) { try { $a.Dispose() } catch { } }
        $script:ZsOpened.Clear()
        if ($archive) { $archive.Dispose() }
        if (Test-Path -LiteralPath $script:ZsTempDir) { Remove-Item -LiteralPath $script:ZsTempDir -Recurse -Force -ErrorAction SilentlyContinue }
    }

    # ---- Final names ----
    $digits = [Math]::Max(2, ([string]$tempParts.Count).Length)
    $finalNames = New-Object System.Collections.Generic.List[string]
    for ($k = 0; $k -lt $tempParts.Count; $k++) {
        $finalNames.Add($base + '_part' + ([string]($k + 1)).PadLeft($digits, '0') + '.zip')
    }

    # Rewrite the REJOIN notes now that the real part names are known.
    foreach ($info in $splitFiles) {
        $info.PartNames.Clear()
        $info.PartNames.Add($finalNames[$info.PartIndexes[0] - 1])
        $info.PartNames.Add($finalNames[$info.PartIndexes[$info.PartIndexes.Count - 1] - 1])
        $txt = Get-ZsRejoinText $info
        foreach ($pit in $info.TextPartItems) { if ($pit.Kind -eq 'text') { $pit.Text = $txt } }
        [void](Write-ZsPart $info.TextPart $info.TextPartItems)
    }

    # Rename and label every part (_zipsplitter_part.json).
    $results = [System.Collections.Generic.List[object]]::new()
    $owned = New-Object System.Collections.Generic.List[string]
    $apps = $null
    try {
        for ($k = 0; $k -lt $tempParts.Count; $k++) {
            $dest = Join-Path $OutputDir $finalNames[$k]
            if (Test-Path -LiteralPath $dest) { throw ('The output folder already contains ' + $finalNames[$k]) }
            Move-Item -LiteralPath $tempParts[$k] -Destination $dest
            $owned.Add($dest)
            $stub = ConvertTo-ZsJsonObject @('format', 'zipsplitter-part', 'version', 1, 'setId', $setId, 'part', ($k + 1), 'partCount', $tempParts.Count, 'originalName', $srcInfo.Name, 'tool', $script:ZsToolName)
            $size = Add-ZsZipEntryText $dest $script:ZsStubName $stub
            if ($size -gt $LimitBytes) { throw ('Internal error: ' + $finalNames[$k] + ' exceeded the limit after adding the part label.') }
            $results.Add((New-Object PSObject -Property @{ Path = $dest; Size = $size }))
        }

        if ($splitFiles.Count -gt 0) {
            $all = New-Object System.Text.StringBuilder
            [void]$all.AppendLine('Some files were too large for a single ' + [Math]::Round($LimitBytes / 1MB, 2) + ' MB zip and were cut into pieces.')
            [void]$all.AppendLine('AgentParcel ("Rebuild from parts") joins them automatically. To do it by hand:')
            [void]$all.AppendLine('')
            foreach ($info in $splitFiles) { [void]$all.AppendLine((Get-ZsRejoinText $info)); [void]$all.AppendLine('----------------------------------------') }
            $notePath = Join-Path $OutputDir 'REJOIN_INSTRUCTIONS.txt'
            [System.IO.File]::WriteAllText($notePath, $all.ToString())
            $owned.Add($notePath)
        }

        if ($IncludeApps) {
            Report-ZsProgress 'Adding AgentParcel-apps.zip...'
            try { $apps = Write-ZsAppsBundle $OutputDir $LimitBytes }
            catch { $apps = New-Object PSObject -Property @{ Path = $null; Size = 0; Note = ('Apps bundle could not be created: ' + $_.Exception.Message) } }
            if ($apps -and $apps.Path) { $owned.Add([string]$apps.Path) }
        }
        foreach ($k in @(Write-ZsZipKit $OutputDir $srcInfo.Name $results $LimitBytes $setId)) { $owned.Add($k) }
    } catch {
        foreach ($t in @($tempParts)) { if ($t -and (Test-Path -LiteralPath $t)) { Remove-Item -LiteralPath $t -Force -ErrorAction SilentlyContinue } }
        Remove-ZsOwned $owned $OutputDir $createdDir
        throw
    }

    $script:ZsDoneWork = $script:ZsTotalWork
    Report-ZsProgress 'Done.'
    return (New-Object PSObject -Property @{ OutputDir = $OutputDir; Parts = $results; SplitFiles = $splitFiles; LimitBytes = $LimitBytes; UnpackedZips = $script:ZsUnpacked.ToArray(); UnpackFailed = $script:ZsUnpackFailed.ToArray(); SetId = $setId; Apps = $apps; Mode = 'zip' })
}

function Format-ZsSummary($Result) {
    $sb = New-Object System.Text.StringBuilder
    if ($Result.Mode -eq 'bytes') { [void]$sb.AppendLine('Created ' + $Result.Parts.Count + ' byte part(s) in:') }
    else { [void]$sb.AppendLine('Created ' + $Result.Parts.Count + ' zip part(s) in:') }
    [void]$sb.AppendLine('  ' + $Result.OutputDir)
    foreach ($p in $Result.Parts) {
        [void]$sb.AppendLine(('  {0}  {1:N2} MB' -f [System.IO.Path]::GetFileName($p.Path), ($p.Size / 1MB)))
    }
    if ($Result.UnpackedZips.Count -gt 0) {
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine('Unpacked ' + $Result.UnpackedZips.Count + ' zip(s) found inside the zip; their contents are in folders named after them.')
        [void]$sb.AppendLine('"Rebuild from parts" turns them back into the original inner zips.')
    }
    if ($Result.UnpackFailed.Count -gt 0) {
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine('Could not open ' + $Result.UnpackFailed.Count + ' inner zip(s) (corrupt or encrypted?); kept them as plain files:')
        foreach ($f in $Result.UnpackFailed) { [void]$sb.AppendLine('  ' + $f) }
    }
    if ($Result.SplitFiles.Count -gt 0) {
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine('NOTE: ' + $Result.SplitFiles.Count + ' file(s) were too big for one part and were cut into pieces (.001, .002, ...):')
        foreach ($s in $Result.SplitFiles) { [void]$sb.AppendLine('  ' + $s.Name + '  (' + $s.Pieces.Count + ' pieces)') }
        [void]$sb.AppendLine('"Rebuild from parts" joins them automatically (or see REJOIN_INSTRUCTIONS.txt).')
    }
    $how = Join-Path $Result.OutputDir 'HOW-TO-REBUILD.txt'
    if (Test-Path -LiteralPath $how) {
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine('HOW-TO-REBUILD.txt and rebuild.py are in that folder.')
        if ($Result.Mode -eq 'bytes') { [void]$sb.AppendLine('The parts are raw pieces of the original file.') }
    }
    if ($Result.Apps) {
        [void]$sb.AppendLine('')
        if ($Result.Apps.Path) {
            [void]$sb.AppendLine(('Included {0} ({1:N0} KB): AgentParcel for Windows, Mac and Linux, so the' -f [System.IO.Path]::GetFileName($Result.Apps.Path), ($Result.Apps.Size / 1KB)))
            [void]$sb.AppendLine('recipient can rebuild. Send it along with the parts (it is not a part).')
        } elseif ($Result.Apps.Note) { [void]$sb.AppendLine('NOTE: ' + $Result.Apps.Note) }
    }
    return $sb.ToString()
}

